import os
import csv
from collections import defaultdict

os.makedirs("data", exist_ok=True)

valid_records = []
rejected_records = []

with open("data/shift_log.txt", "r") as file:
    lines = file.readlines()

for line_number, line in enumerate(lines, start=1):
    line = line.strip()

    try:
        parts = line.split(",")

        if len(parts) != 4:
            raise ValueError("Incorrect number of fields")

        wo, machine, status, time = [p.strip() for p in parts]

        if not wo.startswith("WO") or not wo[2:].isdigit():
            raise ValueError("Invalid work order")

        if not machine:
            raise ValueError("Missing machine")

        if status not in ["Running", "Stopped", "Maintenance"]:
            raise ValueError("Invalid status")

        if len(time) != 5 or time[2] != ":":
            raise ValueError("Invalid time format")

        hour, minute = time.split(":")

        if not hour.isdigit() or not minute.isdigit():
            raise ValueError("Invalid time")

        if not (0 <= int(hour) <= 23 and 0 <= int(minute) <= 59):
            raise ValueError("Time out of range")

        valid_records.append((wo, machine, status, time))

    except ValueError as error:
        rejected_records.append((line_number, line, str(error)))

summary = defaultdict(int)

for wo, machine, status, time in valid_records:
    summary[machine] += 1

with open("data/report.txt", "w") as file:
    file.write("SHIFT LOG REPORT\n")
    file.write("=" * 65 + "\n")
    file.write(f"{'WORK ORDER':<15}{'MACHINE':<15}{'STATUS':<18}{'TIME':<10}\n")
    file.write("-" * 65 + "\n")

    for wo, machine, status, time in valid_records:
        file.write(f"{wo:<15}{machine:<15}{status:<18}{time:<10}\n")

    file.write("-" * 65 + "\n")
    file.write(f"\nTotal valid records: {len(valid_records)}\n")
    file.write(f"Total rejected records: {len(rejected_records)}\n")

    file.write("\nMACHINE SUMMARY\n")
    for machine, count in sorted(summary.items()):
        file.write(f"{machine:<20}{count}\n")

with open("data/rejects.csv", "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["Line Number", "Rejected Line", "Reason"])
    writer.writerows(rejected_records)

