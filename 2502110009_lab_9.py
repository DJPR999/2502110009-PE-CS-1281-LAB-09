import os
import re
import csv
from datetime import datetime
from collections import defaultdict

os.makedirs("data", exist_ok=True)

pattern = r"^\s*(WO\d{3})\s*,\s*([^,]+?)\s*,\s*(Running|Stopped|Maintenance)\s*,\s*(\d{2}:\d{2})\s*$"

plant_summary = defaultdict(int)
total_processed = 0
total_rejected = 0

for filename in os.listdir("data"):

    if not filename.endswith(".txt"):
        continue

    filepath = os.path.join("data", filename)

    valid_records = []
    rejected_records = []

    with open(filepath, "r") as file:
        for line_number, line in enumerate(file, start=1):
            match = re.match(pattern, line)

            if match:
                wo, machine, status, time = match.groups()

                hour, minute = map(int, time.split(":"))

                if 0 <= hour <= 23 and 0 <= minute <= 59:
                    valid_records.append((wo, machine.strip(), status, time))
                    plant_summary[machine.strip()] += 1
                else:
                    rejected_records.append((line_number, line.strip(), "Invalid time"))
            else:
                rejected_records.append((line_number, line.strip(), "Invalid record format"))

    report_name = filename.replace(".txt", "_report.txt")
    report_path = os.path.join("data", report_name)

    with open(report_path, "w") as report:
        report.write("SHIFT LOG REPORT\n")
        report.write("=" * 60 + "\n")
        report.write(f"{'WORK ORDER':<15}{'MACHINE':<15}{'STATUS':<18}{'TIME':<10}\n")
        report.write("-" * 60 + "\n")

        for wo, machine, status, time in valid_records:
            report.write(f"{wo:<15}{machine:<15}{status:<18}{time:<10}\n")

        report.write("-" * 60 + "\n")
        report.write(f"Records processed: {len(valid_records)}\n")
        report.write(f"Rejected records: {len(rejected_records)}\n")

    total_processed += len(valid_records)
    total_rejected += len(rejected_records)

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    history_path = "data/run_history.csv"
    file_exists = os.path.exists(history_path)

    with open(history_path, "a", newline="") as history:
        writer = csv.writer(history)

        if not file_exists:
            writer.writerow(["Timestamp", "File Name", "Records Processed", "Rejects"])

        writer.writerow([
            timestamp,
            filename,
            len(valid_records),
            len(rejected_records)
        ])

with open("data/plant_summary.txt", "w") as summary:
    summary.write("COMBINED PLANT SUMMARY\n")
    summary.write("=" * 40 + "\n")

    for machine, count in sorted(plant_summary.items()):
        summary.write(f"{machine:<20}{count}\n")

    summary.write("-" * 40 + "\n")
    summary.write(f"Total valid records: {total_processed}\n")
    summary.write(f"Total rejected records: {total_rejected}\n")

print("BATCH JOB COMPLETED")
print("Total valid records:", total_processed)
print("Total rejected records:", total_rejected)
print("Individual reports created.")
print("Plant summary saved.")
print("Run history updated.")